def fmt(value: float) -> str:
    return f"{value:g}"


def holes():
    p = PLATE
    s, o = p["side"], p["corner_offset"]
    corners = [(o, o), (s - o, o), (o, s - o), (s - o, s - o)]
    return [(x, y, p["corner_hole_d"]) for x, y in corners] + [(x, y, p["tie_hole_d"]) for x, y in p["tie_holes"]]


def slots():
    p = PLATE
    c = p["side"] / 2.0
    w, length = p["strap_slot"]
    return [(c - p["strap_slot_x"], c, w, length), (c + p["strap_slot_x"], c, w, length)]


# ------------------------------------------------------------------ CAD files
def scad() -> str:
    p = PLATE
    lines = [
        f"// Carrier plate SLM-PAS-M01, revision {REVISION}, {DATE}. Millimetres. Generated by hardware/make_cad.py.",
        "// S&L Milestone Solutions. Preliminary: not cut or fitted. Measure the purchased case before cutting.",
        "$fn = 64;",
        f"plate_side = {p['side']};",
        f"plate_thickness = {p['thickness']};",
        "",
        "module slot(x, y, w, len) {",
        "    hull() {",
        "        translate([x, y - (len - w) / 2, -1]) cylinder(h = plate_thickness + 2, d = w);",
        "        translate([x, y + (len - w) / 2, -1]) cylinder(h = plate_thickness + 2, d = w);",
        "    }",
        "}",
        "",
        "difference() {",
        "    cube([plate_side, plate_side, plate_thickness]);",
    ]
    for x, y, d in holes():
        lines.append(f"    translate([{x}, {y}, -1]) cylinder(h = plate_thickness + 2, d = {d});")
    for x, y, w, length in slots():
        lines.append(f"    slot({x}, {y}, {w}, {length});")
    lines += ["}", "",
              "// Reference only: listed case outline. Remove before export.",
              f"%translate([plate_side / 2, plate_side / 2, plate_thickness + 10]) cylinder(h = 10, d = {p['case_d']});",
              ""]
    return "\n".join(lines)


def dxf() -> str:
    out = ["0", "SECTION", "2", "ENTITIES"]

    def line(x1, y1, x2, y2, layer="CUT"):
        out.extend(["0", "LINE", "8", layer, "10", f"{x1:.3f}", "20", f"{y1:.3f}", "11", f"{x2:.3f}", "21", f"{y2:.3f}"])

    def circle(x, y, r, layer="CUT"):
        out.extend(["0", "CIRCLE", "8", layer, "10", f"{x:.3f}", "20", f"{y:.3f}", "40", f"{r:.3f}"])

    def arc(x, y, r, a0, a1, layer="CUT"):
        out.extend(["0", "ARC", "8", layer, "10", f"{x:.3f}", "20", f"{y:.3f}", "40", f"{r:.3f}", "50", f"{a0:.1f}", "51", f"{a1:.1f}"])

    s = PLATE["side"]
    for x1, y1, x2, y2 in ((0, 0, s, 0), (s, 0, s, s), (s, s, 0, s), (0, s, 0, 0)):
        line(x1, y1, x2, y2)
    for x, y, d in holes():
        circle(x, y, d / 2.0)
    for x, y, w, length in slots():
        r, half = w / 2.0, (length - w) / 2.0
        line(x - r, y - half, x - r, y + half)
        line(x + r, y - half, x + r, y + half)
        arc(x, y + half, r, 0.0, 180.0)
        arc(x, y - half, r, 180.0, 360.0)
    c = s / 2.0
    circle(c, c, PLATE["case_d"] / 2.0, "REFERENCE_DO_NOT_CUT")
    zx, zy = PLATE["match_drill_zone"]
    for x1, y1, x2, y2 in ((c - zx / 2, c - zy / 2, c + zx / 2, c - zy / 2), (c + zx / 2, c - zy / 2, c + zx / 2, c + zy / 2),
                           (c + zx / 2, c + zy / 2, c - zx / 2, c + zy / 2), (c - zx / 2, c + zy / 2, c - zx / 2, c - zy / 2)):
        line(x1, y1, x2, y2, "REFERENCE_DO_NOT_CUT")
    out.extend(["0", "ENDSEC", "0", "EOF"])
    return "\n".join(out) + "\n"


# ------------------------------------------------------------- sheet helpers
def title_info(number, title, subtitle, scale, sheet, material, tolerances, finish="NONE"):
    return {"number": number, "title": title, "subtitle": subtitle, "scale": scale, "sheet": sheet, "size": "B",
            "rev": REVISION, "project": PROJECT, "status": "PRELIMINARY", "material": material, "finish": finish,
            "tolerances": tolerances, "signoff": [("DRAWN", "", DATE), ("CHECKED", "", ""), ("APPROVED", "", "")]}


REVISIONS = [(REVISION, "INITIAL ISSUE. REPLACES REV B SKETCHES", DATE, "")]
NOTES_X, NOTES_Y = 270.0, 37.0


def edge_point(cx, cy, r, toward_x, toward_y):
    """Point on a circle nearest to another point: where a leader should end."""
    d = math.hypot(toward_x - cx, toward_y - cy)
    return cx + r * (toward_x - cx) / d, cy + r * (toward_y - cy) / d


def draw_slot(sheet, cx, cy, w, length, kind="visible"):
    r, half = w / 2.0, (length - w) / 2.0
    sheet.line(cx - r, cy - half, cx - r, cy + half, kind)
    sheet.line(cx + r, cy - half, cx + r, cy + half, kind)
    sheet.arc(cx, cy - half, r, 0, 180, kind)
    sheet.arc(cx, cy + half, r, 180, 360, kind)


