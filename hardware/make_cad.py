def outputs() -> dict:
    """Every generated file as {relative path: text or bytes}."""
    files = {"cad/carrier.scad": scad(), "cad/carrier.dxf": dxf()}
    built = []
    for number, make in SHEETS:
        sheet = make()
        built.append(sheet)
        files[f"drawings/{number}.svg"] = sheet.to_svg()
        files[f"drawings/{number}.pdf"] = write_pdf([sheet], number)
    files["drawings/SLM-PAS-DRAWING-SET.pdf"] = write_pdf(built, "SLM-PAS drawing set")
    return files


def main() -> None:
    root = Path(__file__).resolve().parent
    for name, content in outputs().items():
        path = root / name
        path.parent.mkdir(exist_ok=True)
        if isinstance(content, bytes):
            path.write_bytes(content)
        else:
            path.write_text(content, encoding="utf-8", newline="\n")
        print(f"wrote hardware/{name}")


if __name__ == "__main__":
    main()
